import type { DeploymentRecord } from "./deployment";

export interface VerificationResult {
  deployment: DeploymentRecord;
  receiptSucceeded: boolean;
  receiptMatchesTransaction: boolean;
  receiptCreatedContract: boolean;
  receiptSentByDeployer: boolean;
  receiptMatchesBlock: boolean;
  runtimeBytecodeMatches: boolean;
  bytecodePresent: boolean;
  owner: string;
  ownerMatches: boolean;
  message: string;
  messageMatches: boolean;
  updatedAt: bigint;
}

export function renderDeploymentReport(result: VerificationResult): string {
  const checks = [
    result.receiptSucceeded,
    result.receiptMatchesTransaction,
    result.receiptCreatedContract,
    result.receiptSentByDeployer,
    result.receiptMatchesBlock,
    result.runtimeBytecodeMatches,
    result.bytecodePresent,
    result.ownerMatches,
    result.messageMatches,
    result.updatedAt > 0n
  ];

  if (checks.some((check) => !check)) {
    throw new Error(
      "Cannot generate a PASS report because one or more verification checks failed."
    );
  }

  const { deployment } = result;
  const escapedMessage = result.message.replace(/[\\`*_[\]()<>!]/g, "\\$&");

  return `# Arc Testnet Deployment Verification

**Overall result:** PASS

This report was generated by reading the deployed contract and transaction
directly from the Arc Testnet RPC.

## Public Evidence

| Field | Value |
| --- | --- |
| Network | ${deployment.network} |
| Chain ID | ${deployment.chainId} |
| Deployer | \`${deployment.deployer}\` |
| Contract | [\`${deployment.contractAddress}\`](${deployment.contractUrl}) |
| Transaction | [\`${deployment.transactionHash}\`](${deployment.transactionUrl}) |
| Block | ${deployment.blockNumber} |
| Deployed at | ${deployment.deployedAt} |

## Verification Checks

- [x] Transaction receipt succeeded
- [x] Receipt transaction hash matches the deployment
- [x] Receipt created the recorded contract
- [x] Receipt sender matches the deployer
- [x] Receipt block matches the deployment
- [x] Runtime bytecode matches the compiled contract
- [x] Contract bytecode exists
- [x] Onchain owner matches the deployer
- [x] Onchain message matches the deployment
- [x] Onchain update timestamp is present

## Onchain Values

- **Owner:** \`${result.owner}\`
- **Message:** ${escapedMessage}
- **Updated at:** ${result.updatedAt}

## Reproduce

\`\`\`powershell
npm install
npm run verify
\`\`\`
`;
}
